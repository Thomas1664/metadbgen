"""
Parse a Snakemake log file and produce a JSON summary of job execution times,
grouped by rule. Each job entry includes duration, input/output files,
wildcards, and resources.

Usage:
    python parse_snakemake_log.py [<logfile>] [--output <out.json>]

If <logfile> is omitted, the newest file in .snakemake/log/ is used.

Generated by Claude Sonnet 4.6
"""

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path

TIMESTAMP_RE = re.compile(r"^\[(\w{3} \w{3}\s+\d+ \d{2}:\d{2}:\d{2} \d{4})\]$")
RULE_RE = re.compile(r"^(?:local)?rule (\w+):$")
FIELD_RE = re.compile(r"^    (\w+): (.*)$")
JOBID_RE = re.compile(r"^    jobid: (\d+)$")
FINISHED_RE = re.compile(r"^Finished jobid: (\d+) \(Rule: (\w+)\)$")
TIMESTAMP_FMT = "%a %b %d %H:%M:%S %Y"


def parse_csv_field(value: str) -> list[str]:
    return [v.strip() for v in value.split(",") if v.strip()]


def parse_kv_field(value: str) -> dict[str, str]:
    result = {}
    for part in value.split(","):
        part = part.strip()
        if "=" in part:
            k, _, v = part.partition("=")
            result[k.strip()] = v.strip()
        elif part:
            result[part] = ""
    return result


def parse_log(path: Path) -> dict:
    lines = path.read_text().splitlines()

    pending_jobs: dict[int, dict] = {}   # jobid -> job info
    completed_jobs: list[dict] = []

    i = 0
    current_ts: datetime | None = None

    while i < len(lines):
        line = lines[i]

        # Capture timestamp lines
        ts_match = TIMESTAMP_RE.match(line)
        if ts_match:
            current_ts = datetime.strptime(ts_match.group(1), TIMESTAMP_FMT)
            i += 1
            continue

        # Check for a rule header (job start)
        rule_match = RULE_RE.match(line)
        if rule_match and current_ts is not None:
            rule_name = rule_match.group(1)
            job: dict = {
                "rule": rule_name,
                "start": current_ts.isoformat(),
                "input": [],
                "output": [],
                "jobid": None,
                "reason": "",
                "wildcards": {},
                "resources": {},
            }
            i += 1
            # Parse indented fields until a non-indented line
            while i < len(lines) and lines[i].startswith("    "):
                field_line = lines[i]
                jobid_match = JOBID_RE.match(field_line)
                if jobid_match:
                    job["jobid"] = int(jobid_match.group(1))
                    i += 1
                    continue

                field_match = FIELD_RE.match(field_line)
                if field_match:
                    key, value = field_match.group(1), field_match.group(2)
                    if key == "input":
                        job["input"] = parse_csv_field(value)
                    elif key == "output":
                        job["output"] = parse_csv_field(value)
                    elif key == "wildcards":
                        job["wildcards"] = parse_kv_field(value)
                    elif key == "resources":
                        job["resources"] = parse_kv_field(value)
                    elif key == "reason":
                        job["reason"] = value
                i += 1

            if job["jobid"] is not None:
                pending_jobs[job["jobid"]] = job
            continue

        # Check for a "Finished" line
        fin_match = FINISHED_RE.match(line)
        if fin_match and current_ts is not None:
            jobid = int(fin_match.group(1))
            if jobid in pending_jobs:
                job = pending_jobs.pop(jobid)
                start = datetime.fromisoformat(job["start"])
                duration_s = (current_ts - start).total_seconds()
                job["end"] = current_ts.isoformat()
                job["duration_seconds"] = duration_s
                completed_jobs.append(job)
            i += 1
            continue

        i += 1

    # Group by rule
    by_rule: dict[str, list[dict]] = {}
    for job in completed_jobs:
        rule = job["rule"]
        by_rule.setdefault(rule, [])
        entry = {
            "jobid": job["jobid"],
            "start": job["start"],
            "end": job["end"],
            "duration_seconds": job["duration_seconds"],
            "wildcards": job["wildcards"],
            "input": job["input"],
            "output": job["output"],
            "resources": job["resources"],
            "reason": job["reason"],
        }
        by_rule[rule].append(entry)

    # Summary stats per rule
    summary: dict[str, dict] = {}
    for rule, jobs in by_rule.items():
        durations = [j["duration_seconds"] for j in jobs]
        summary[rule] = {
            "job_count": len(jobs),
            "total_duration_seconds": sum(durations),
            "min_duration_seconds": min(durations),
            "max_duration_seconds": max(durations),
            "jobs": jobs,
        }

    return summary


def find_latest_log(log_dir: Path = Path(".snakemake/log")) -> Path:
    logs = sorted(log_dir.glob("*.snakemake.log"))
    if not logs:
        raise FileNotFoundError(f"No Snakemake log files found in {log_dir}")
    return logs[-1]


def main() -> None:
    parser = argparse.ArgumentParser(description="Parse a Snakemake log into JSON.")
    parser.add_argument(
        "logfile", type=Path, nargs="?", default=None,
        help="Path to the Snakemake log file (default: newest file in .snakemake/log/).",
    )
    parser.add_argument(
        "--output", "-o", type=Path, default=None,
        help="Output JSON file (default: print to stdout).",
    )
    args = parser.parse_args()

    if args.logfile is None:
        try:
            args.logfile = find_latest_log()
            print(f"Using log file: {args.logfile}", file=sys.stderr)
        except FileNotFoundError as e:
            print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)

    if not args.logfile.exists():
        print(f"Error: {args.logfile} does not exist.", file=sys.stderr)
        sys.exit(1)

    result = parse_log(args.logfile)
    json_str = json.dumps(result, indent=2)

    if args.output:
        args.output.write_text(json_str)
        print(f"Written to {args.output}")
    else:
        print(json_str)


if __name__ == "__main__":
    main()
